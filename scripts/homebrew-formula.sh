#!/bin/sh
# Print the Homebrew formula for an msn release.
#   scripts/homebrew-formula.sh v0.1.14 DIR > Formula/msn.rb
# DIR holds the release's msn-<tag>-<target>.tar.gz.sha256 files (release.yml's
# artifacts directory). Run by release.yml after each release; also by hand.
set -eu
tag="$1"
dir="$2"
case "$tag" in
v[0-9]*) ;;
*)
  echo "usage: $0 vX.Y.Z DIR" >&2
  exit 2
  ;;
esac
sum() {
  file="$dir/msn-$tag-$1.tar.gz.sha256"
  hash="$(cut -d ' ' -f 1 <"$file")"
  [ ${#hash} -eq 64 ] || {
    echo "bad checksum in $file" >&2
    exit 1
  }
  printf '%s' "$hash"
}
base="https://github.com/thehumanworks/msn/releases/download/$tag/msn-$tag"
cat <<RUBY
# Generated by scripts/homebrew-formula.sh from the $tag release. Do not edit.
#   brew tap thehumanworks/msn https://github.com/thehumanworks/msn
#   brew install thehumanworks/msn/msn
class Msn < Formula
  desc "Agent message boards with shared channel access"
  homepage "https://github.com/thehumanworks/msn"
  version "${tag#v}"

  on_macos do
    on_arm do
      url "$base-aarch64-apple-darwin.tar.gz"
      sha256 "$(sum aarch64-apple-darwin)"
    end
    on_intel do
      url "$base-x86_64-apple-darwin.tar.gz"
      sha256 "$(sum x86_64-apple-darwin)"
    end
  end

  on_linux do
    on_arm do
      url "$base-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$(sum aarch64-unknown-linux-gnu)"
    end
    on_intel do
      url "$base-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$(sum x86_64-unknown-linux-gnu)"
    end
  end

  def install
    bin.install "msn"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/msn --version")
  end
end
RUBY
